from konlpy.tag import Okt
from tqdm.auto import tqdm
tqdm.pandas()

TEXT_COLS = [col for col in df.columns if col not in EXCLUDE_COLS]
print(f"✅ '{', '.join(EXCLUDE_COLS)}' 제외한 {len(TEXT_COLS)}개 컬럼을 텍스트 분석에 사용합니다.")
STOPWORDS = {'및', '등', '관련', '필요', '가능', '분야'}
okt = Okt()
def clean_text(txt):
    nouns = [n for n in okt.nouns(str(txt)) if n not in STOPWORDS and len(n) > 1]
    return ' '.join(nouns)

df['text_raw'] = df[TEXT_COLS].astype(str).fillna('').agg(' '.join, axis=1)
df['cleaned_text'] = df['text_raw'].progress_apply(clean_text)
print("✅ 텍스트 전처리 완료.")

# =========================================================
# 4~5단계: TF-IDF 추출 및 Wide Format으로 병합
# =========================================================

# 4) TF-IDF 벡터화
from sklearn.feature_extraction.text import TfidfVectorizer
vec = TfidfVectorizer(token_pattern=r'(?u)\b\w+\b', min_df=5, max_df=0.8)
tfidf_matrix = vec.fit_transform(df['cleaned_text'])
vocab = vec.get_feature_names_out()
print("✅ TF-IDF 벡터화 완료.")

# 5) TF-IDF 상위 10개 키워드 추출 (Wide Format)
def get_top_10_keywords_list(row, vocab):
    if row.nnz == 0:
        return [None] * 10 # 10개의 빈 리스트

    best_idx = row.indices[row.data.argsort()[::-1][:10]]
    keywords = [vocab[i] for i in best_idx]

    # 10개 미만일 경우 None으로 채우기
    if len(keywords) < 10:
        keywords.extend([None] * (10 - len(keywords)))

    return keywords

print("⏳ TF-IDF Top 10 키워드 리스트 추출 중...")
keyword_data = [get_top_10_keywords_list(tfidf_matrix[i], vocab)
                for i in tqdm(range(tfidf_matrix.shape[0]), desc="TF-IDF Top 10 추출 중")]

# 새 컬럼명 생성 (키워드1, 키워드2, ...)
keyword_column_names = [f'키워드{i+1}' for i in range(10)]

# 리스트 데이터를 DataFrame으로 변환
df_keywords = pd.DataFrame(keyword_data, columns=keyword_column_names, index=df.index)

# 원본 DataFrame에 병합
df = pd.concat([df, df_keywords], axis=1)
print("✅ TF-IDF 기반 상위 10개 키워드 컬럼 추가 완료.")

# =========================================================
# 🆕 6~7단계: [신규] 최종 포맷 정리 및 저장
# =========================================================

print("💾 최종 저장 포맷(Wide format)으로 변환을 시작합니다...")

# 6) 최종 포맷 정리
id_col = EXCLUDE_COLS[0]   # 예: 'major_id'
name_col = NAME_COL       # 예: '학과명'

# 요청된 컬럼 리스트
output_columns = [
    id_col,
    name_col,
    'cleaned_text',
] + keyword_column_names # [f'키워드{i+1}' for i in range(10)]

# 원본 df에서 필요한 컬럼만 선택
df_final_output = df[output_columns]

# 컬럼명 변경 (요청사항에 맞게)
df_final_output = df_final_output.rename(columns={
    id_col: 'id',
    name_col: NAME_COL, # NAME_COL 변수값(예: '학과명')
    'cleaned_text': '클리어링텍스트'
})

# 7) 최종 결과 CSV 저장
FINAL_OUTPUT_PATH = DRIVE_PATH + OUTPUT_FILE

df_final_output.to_csv(FINAL_OUTPUT_PATH, index=False, encoding='utf-8-sig')
print(f"💾 TF-IDF Top 10 키워드({FINAL_OUTPUT_PATH}) 저장 완료")

