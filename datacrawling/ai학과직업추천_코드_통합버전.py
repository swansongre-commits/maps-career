def setup_driver():
    """Selenium WebDriver를 headless 모드로 설정합니다."""
    chrome_options = Options()
    chrome_options.add_argument('--headless')
    chrome_options.add_argument('--no-sandbox')
    chrome_options.add_argument('--disable-dev-shm-usage')

    service = Service(ChromeDriverManager().install())
    driver = webdriver.Chrome(service=service, options=chrome_options)
    driver.implicitly_wait(5) # 암묵적 대기 시간 설정
    return driver

def get_content_after_heading(heading_tag):
    """
    주어진 제목(heading) 태그 다음에 오는 콘텐츠 블록(ul, div 등)을 찾아
    텍스트를 추출하는 보조 함수입니다.
    """
    for sibling in heading_tag.find_next_siblings():
        # 콘텐츠를 담고 있는 일반적인 태그들을 확인합니다.
        if sibling.name in ['ul', 'div', 'p', 'table']:
            if sibling.name == 'ul':
                # <ul> 태그의 경우, 모든 <li> 항목을 쉼표로 구분하여 합칩니다.
                return ', '.join(li.get_text(strip=True) for li in sibling.find_all('li'))
            else:
                # 그 외의 경우, 전체 텍스트를 공백으로 구분하여 가져옵니다.
                return sibling.get_text(separator=' ', strip=True)
        # 다른 제목 태그를 만나면 검색을 중단합니다.
        if sibling.name in ['h3', 'h4'] and 'com-conts-title' in sibling.get('class', []):
            break
    return ""

def crawl_major_info(seq_list):
    """주어진 seq 리스트를 순회하며 학과 정보를 크롤링합니다."""
    driver = setup_driver()
    all_departments_data = []

    print(f"🚀 Starting crawling for {len(seq_list)} departments...")

    for seq in seq_list:
        url = f"https://www.career.go.kr/cloud/w/major/uView?seq={seq}"

        try:
            driver.get(url)
            # 학과명이 포함된 제목 태그가 화면에 보일 때까지 명시적으로 대기합니다.
            title_element = WebDriverWait(driver, 10).until(
                EC.visibility_of_element_located((By.CSS_SELECTOR, "div.title-box > h2"))
            )

            department_name = title_element.text.strip()

            if not department_name:
                print(f"⚠️ Skipping seq {seq}: Department name is empty.")
                continue

            current_data = {'seq': seq, '학과명': department_name}
            print(f"🔍 Crawling: seq={seq}, 학과명={department_name}")

            # --- [개선된 로직] 탭별 정보 추출 ---
            # 크롤링할 탭 목록을 정의합니다.
            TABS_TO_CRAWL = ["학과개요", "개설대학", "학과전망", "학과인터뷰"]

            for tab_name in TABS_TO_CRAWL:
                try:
                    # XPath를 사용하여 탭 이름으로 버튼을 정확하게 찾습니다.
                    tab_button_xpath = f"//ul[contains(@class, 'com-tab')]/li/button[contains(text(), '{tab_name}')]"
                    tab_button = WebDriverWait(driver, 5).until(
                        EC.element_to_be_clickable((By.XPATH, tab_button_xpath))
                    )

                    # JavaScript를 사용하여 안정적으로 스크롤하고 클릭합니다.
                    driver.execute_script("arguments[0].scrollIntoView({block: 'center'});", tab_button)
                    time.sleep(0.5)
                    driver.execute_script("arguments[0].click();", tab_button)
                    time.sleep(1.2) # 콘텐츠가 로드될 시간을 줍니다.

                    tab_soup = BeautifulSoup(driver.page_source, 'html.parser')
                    content_area = tab_soup.select_one('div.ji-conts-box')
                    if not content_area:
                        continue

                    # --- 탭별 맞춤형 데이터 추출 로직 ---
                    if tab_name == "학과개요":
                        h3_sections = content_area.select('h3.com-conts-title.md')
                        for h3 in h3_sections:
                            h3_title = h3.get_text(strip=True)
                            column_name = f"{tab_name}_{h3_title}"
                            parent_div = h3.find_parent('div', class_='com-conts-area')
                            if not parent_div: continue
                            h4_sections = parent_div.select('h4.com-conts-title.sm')
                            if h4_sections:
                                content_parts = [f"{h4.get_text(strip=True)}: {get_content_after_heading(h4)}" for h4 in h4_sections]
                                final_content = " | ".join(content_parts)
                            else:
                                final_content = get_content_after_heading(h3)
                            current_data[column_name] = final_content

                    elif tab_name == "개설대학":
                        table = content_area.select_one('table.com-table')
                        if table:
                            uni_list = []
                            for row in table.select('tbody tr'):
                                cols = [td.get_text(strip=True) for td in row.select('td')]
                                if len(cols) == 3:
                                    uni_list.append(f"{cols[0]}_{cols[1]}_{cols[2]}")
                            current_data[tab_name] = ", ".join(uni_list)

                    elif tab_name == "학과전망":
                        charts = content_area.select('div.com-chartbox-contents')
                        for chart in charts:
                            title_tag = chart.select_one('p.chart-title')
                            if not title_tag: continue
                            chart_title = title_tag.get_text(strip=True)
                            column_name = f"{tab_name}_{chart_title}"

                            content_parts = []
                            legend_items = chart.select('div.chart_legend li')
                            for item in legend_items:
                                text_content = item.get_text(strip=True)
                                # "항목명 수치%" 또는 "항목명 수치" 형태를 분리
                                name_part = ''.join(filter(lambda x: not x.isdigit() and x not in '.,%', text_content)).strip()
                                value_part = ''.join(filter(lambda x: x.isdigit() or x in '.,%', text_content)).strip()
                                content_parts.append(f"{name_part}:{value_part}")

                            source_tag = chart.select_one('div.chart-info p')
                            if source_tag:
                                content_parts.append(source_tag.get_text(strip=True))

                            current_data[column_name] = ", ".join(content_parts)

                    elif tab_name == "학과인터뷰":
                        questions = [q.get_text(strip=True) for q in content_area.select('li.left-box div.question-box')]
                        answers = [a.get_text(strip=True) for a in content_area.select('li.right-box div.answer-box')]

                        interview_pairs = []
                        for q, a in zip(questions, answers):
                            interview_pairs.append(f"질문(궁금해요):{q}, 답변:{a}")

                        if interview_pairs:
                            current_data[tab_name] = ", ".join(interview_pairs)

                except Exception:
                    # 해당 탭이 없거나 클릭할 수 없는 경우, 조용히 넘어갑니다.
                    continue

            all_departments_data.append(current_data)

        except Exception as e:
            print(f"❌ An error occurred while processing seq {seq}: {e}")
            continue

    driver.quit()
    print("✅ Crawling finished.")
    return all_departments_data

def save_to_csv(data, folder_path, filename):
    """크롤링한 데이터를 CSV 파일로 저장합니다."""
    if not data:
        print("ℹ️ No data was crawled. CSV file will not be created.")
        return

    df = pd.DataFrame(data)

    if not os.path.exists(folder_path):
        os.makedirs(folder_path)
        print(f"📂 Created directory: {folder_path}")

    file_path = os.path.join(folder_path, filename)

    df.to_csv(file_path, index=False, encoding='utf-8-sig')
    print(f"💾 Data successfully saved to {file_path}")


