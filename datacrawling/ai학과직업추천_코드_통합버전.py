def extract_text_block(tag):
    sib = tag.find_next_sibling
    for t in ("ul", "div", "span", "p"):
        s = sib(t)
        if s:
            return ", ".join(li.get_text(strip=True) for li in s.select("li")) if t == "ul" else s.get_text(strip=True)
    return None

def extract_sections(soup, store: dict):
    for h3 in soup.select("h3.com-conts-title.md"):
        sec = h3.get_text(strip=True)
        area = h3.find_parent("div", class_="com-conts-area")
        h4s = area.select("h4.com-conts-title.sm")
        if h4s:
            for h4 in h4s:
                store[f"{sec}_{h4.get_text(strip=True)}"] = extract_text_block(h4)
        else:
            store[sec] = extract_text_block(h3)

