"""## 3. Step 1·2 — 순위 점수합 기반 추천 함수

학생의 입력 키워드를 받아 한 코퍼스(학과 또는 직업)에 대해 점수합을 계산한다. 매칭된 키워드 내역도 함께 반환해 추천 근거를 추적할 수 있게 한다.
"""

def rank_score_recommend(user_keywords, df, name_col, top_n=10):
    """순위 점수합 기반 추천

    Args:
        user_keywords (list[str]): 학생 입력 키워드
        df (DataFrame): 학과 또는 직업 데이터프레임 (id, 명칭, 키워드1~10 포함)
        name_col (str): 명칭 컬럼명 ('학과명' 또는 '직업명')
        top_n (int): 반환할 상위 항목 수

    Returns:
        DataFrame: 점수합이 0보다 큰 항목만, 점수합 내림차순으로 상위 top_n개
                   ('id', name_col, 키워드1~10, '점수합', '매칭내역' 컬럼)
    """
    user_set = set(user_keywords)
    scores = []
    matched_descs = []

    for idx in range(len(df)):
        row_score = 0
        row_match = []
        for rank in range(1, 11):
            kw = df.loc[idx, f'키워드{rank}']
            if pd.notna(kw) and kw in user_set:
                pts = RANK_SCORES[rank]
                row_score += pts
                row_match.append(f'{kw}({rank}위·{pts}점)')
        scores.append(row_score)
        matched_descs.append(' / '.join(row_match) if row_match else '')

    result = df[['id', name_col] + kw_cols].copy()
    result['점수합'] = scores
    result['매칭내역'] = matched_descs
    result = result[result['점수합'] > 0].sort_values('점수합', ascending=False).head(top_n)
    return result.reset_index(drop=True)

