"""## 4. Step 3 — 학과 × 직업 연계 페어 (키워드 교집합)

각각 상위 3개씩 뽑아 3×3=9쌍의 페어를 만든 뒤, 학과 TOP10 키워드와 직업 TOP10 키워드의 **교집합 크기**로 정렬한다.

동률이 발생하는 경우 학과 점수합 + 직업 점수합으로 보조 정렬한다 (학생 키워드와의 적합도가 더 높은 쪽이 우선).
"""

def link_major_job(user_keywords, top_n_each=3, top_n_pairs=9):
    """학과×직업 연계 추천: 상위 학과·직업의 키워드 교집합 크기로 정렬

    Args:
        user_keywords (list[str]): 학생 입력 키워드
        top_n_each (int): 각각 추출할 상위 학과/직업 수 (기본 3)
        top_n_pairs (int): 반환할 페어 수 (기본 9 = 3×3 전체)

    Returns:
        (pairs_df, top_majors, top_jobs)
    """
    top_majors = rank_score_recommend(user_keywords, major, '학과명', top_n=top_n_each)
    top_jobs = rank_score_recommend(user_keywords, job, '직업명', top_n=top_n_each)

    if len(top_majors) == 0 or len(top_jobs) == 0:
        return pd.DataFrame(), top_majors, top_jobs

    rows = []
    for mi in range(len(top_majors)):
        m_kws = set(top_majors.loc[mi, kw_cols].dropna().tolist())
        m_name = top_majors.loc[mi, '학과명']
        m_score = top_majors.loc[mi, '점수합']

        for ji in range(len(top_jobs)):
            j_kws = set(top_jobs.loc[ji, kw_cols].dropna().tolist())
            j_name = top_jobs.loc[ji, '직업명']
            j_score = top_jobs.loc[ji, '점수합']

            overlap = m_kws & j_kws
            rows.append({
                '학과명': m_name,
                '학과점수': m_score,
                '직업명': j_name,
                '직업점수': j_score,
                '겹친키워드수': len(overlap),
                '겹친키워드': ', '.join(sorted(overlap)) if overlap else '(없음)',
            })

    pairs = pd.DataFrame(rows)
    pairs['_보조'] = pairs['학과점수'] + pairs['직업점수']
    pairs = pairs.sort_values(['겹친키워드수', '_보조'], ascending=[False, False])
    pairs = pairs.drop(columns=['_보조']).head(top_n_pairs).reset_index(drop=True)
    return pairs, top_majors, top_jobs

"""## 5. 통합 추천 함수 (Step1+2+3)

위 함수들을 묶어 한 번의 호출로 학생 키워드에 대한 전체 추천 결과를 출력한다.
"""

def recommend_career(user_keywords, top_n_each=3, verbose=True):
    """학생 키워드로 학과·직업 추천 + 학과-직업 연계 페어를 출력"""
    pairs, top_majors, top_jobs = link_major_job(
        user_keywords, top_n_each=top_n_each, top_n_pairs=top_n_each * top_n_each
    )

    if not verbose:
        return {'학과': top_majors, '직업': top_jobs, '연계페어': pairs}

    print('=' * 78)
    print(f'입력 키워드: {user_keywords}')
    print('=' * 78)

    if len(top_majors) == 0 and len(top_jobs) == 0:
        print('⚠️ 매칭된 학과·직업이 없습니다. 다른 키워드를 입력해보세요.')
        return {'학과': top_majors, '직업': top_jobs, '연계페어': pairs}

    print(f'\n[Step 1] 📚 추천 학과 Top {top_n_each}')
    if len(top_majors) > 0:
        print(top_majors[['학과명', '점수합', '매칭내역']].to_string(index=False))
    else:
        print('  (매칭 없음)')

    print(f'\n[Step 2] 💼 추천 직업 Top {top_n_each}')
    if len(top_jobs) > 0:
        print(top_jobs[['직업명', '점수합', '매칭내역']].to_string(index=False))
    else:
        print('  (매칭 없음)')

    print(f'\n[Step 3] 🔗 학과-직업 연계 페어 (키워드 교집합 정렬)')
    if len(pairs) > 0:
        print(pairs.to_string(index=False))
    else:
        print('  (페어 생성 불가)')

    return {'학과': top_majors, '직업': top_jobs, '연계페어': pairs}

