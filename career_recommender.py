def call_gpt(student_text, model='gpt-4o-mini', temperature=0.0):
    """학생 발화를 GPT에 전달해 키워드 JSON을 받는다.

    Returns:
        str: GPT의 raw 응답 텍스트
    """
    from openai import OpenAI  # !pip install openai 필요할 수 있음

    client = OpenAI(api_key=get_openai_api_key())
    response = client.chat.completions.create(
        model=model,
        temperature=temperature,
        messages=[
            {'role': 'system', 'content': SYSTEM_PROMPT},
            {'role': 'user', 'content': build_user_prompt(student_text)},
        ],
    )
    return response.choices[0].message.content

# ===== LLM 응답 파싱 =====

def parse_llm_response(response_text):
    """LLM 응답에서 키워드 JSON을 안전하게 파싱한다.

    GPT가 코드블록(```json ... ```)으로 감싸도 정상 처리되도록 한다.
    JSON 파싱 실패 시 정규식으로 키워드 배열만이라도 건진다.
    """
    cleaned = re.sub(r'```json|```', '', response_text).strip()

    try:
        data = json.loads(cleaned)
        return {
            '긍정_키워드': data.get('긍정_키워드', []),
            '부정_제외': data.get('부정_제외', []),
            '근거': data.get('근거', ''),
        }
    except json.JSONDecodeError:
        match = re.search(r'\[(.*?)\]', cleaned, re.DOTALL)
        if match:
            kws = [k.strip().strip('"\\\'') for k in match.group(1).split(',')]
            return {'긍정_키워드': kws, '부정_제외': [], '근거': '(부분 파싱)'}
        return {'긍정_키워드': [], '부정_제외': [], '근거': '(파싱 실패)'}


def extract_keywords_from_speech(student_text, model='gpt-4o-mini'):
    """학생 발화 → GPT 호출 → 키워드 추출 → 파싱 결과 반환"""
    raw = call_gpt(student_text, model=model)
    return parse_llm_response(raw), raw

