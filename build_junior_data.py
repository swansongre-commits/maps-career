def pick_emoji(name, tag):
    hay = (str(name) + " " + str(tag)).lower()
    for kw, em in EMOJI_RULES:
        if kw.lower() in hay:
            return em
    return "💼"

def kidify(text):
    if not isinstance(text, str) or not text.strip():
        return ""
    # 첫 문장만
    seg = re.split(r"[.,]\s|\.$|\n", text.strip())[0].strip()
    seg = seg.rstrip(" .,")
    # 어미 순화
    seg = re.sub(r"합니다$", "해요", seg)
    seg = re.sub(r"됩니다$", "돼요", seg)
    seg = re.sub(r"입니다$", "이에요", seg)
    seg = re.sub(r"있습니다$", "있어요", seg)
    if len(seg) > 48:
        seg = seg[:46].rstrip() + "…"
    return seg

def first_major(s):
    if not isinstance(s, str) or not s.strip():
        return ""
    # 붙어있는 학과명: '학과/공학과/학부/전공' 경계로 첫 항목 추정
    m = re.search(r"^.+?(학과|공학과|학부|전공|과)", s.strip())
    return m.group(0) if m else s.strip()[:12]

